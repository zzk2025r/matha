# 问题 1：直接编译机器码 + 被其他语言解读
# ============================================================
"""
现状：
  Matha → C 代码 → gcc → 机器码  (间接，需要外部工具链)
  Matha → Python 代码 → CPython  (间接，Python解释执行)

方案 A：原生机器码生成器（不依赖 gcc/LLVM）
  ┌─────────────────────────────────────────────────────┐
  │  Matha MIR  →  x86-64 机器码 (直接生成 .o/.exe)     │
  │  Matha MIR  →  ARM64 机器码                          │
  │  Matha MIR  →  WASM 机器码 (wasm32)                  │
  └─────────────────────────────────────────────────────┘

方案 B：FFI 互操作（被其他语言调用）
  - Python: ctypes / cffi 调用编译后的 Matha 动态库
  - Rust:   extern "C" 调用 Matha 生成的 .so/.dll
  - Go:     CGO 调用 Matha 生成的 .so
  - JavaScript: WASM import 调用 Matha 编译的函数
  - C/C++:  #include "matha.h" 直接调用

实现路径：
  1. 先实现 MIR → C 代码生成（已有，但功能有限）
  2. 再用 cffi/ctypes 让 Python 调用编译后的 C 库
  3. 逐步替换为原生机器码生成器
"""


