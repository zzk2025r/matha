@dataclass
class DriverSpec:
    """硬件驱动规格。"""
    name: str
    language: str           # python / c / javascript
    math_func: str          # 数学函数描述
    io_type: str            # input / output / both
    precision: str = "float"
    params: Dict[str, Any] = field(default_factory=dict)


class DriverGenerator:
    """硬件驱动代码生成器。"""

    TARGETS = {
        "python": PythonGenerator,
        "c": CGenerator,
        "javascript": JavaScriptGenerator,
    }

    def __init__(self):
        logger.info("  [CodeGen] 驱动生成器初始化")

    def generate(self, spec: DriverSpec) -> str:
        """根据规格生成驱动代码。"""
        gen_cls = self.TARGETS.get(spec.language, PythonGenerator)
        gen = gen_cls(func_name=spec.name)
        gen.add_expression(spec.math_func)
        code = gen.get_code()
        logger.info(f"  [CodeGen] 生成驱动: {spec.name} ({spec.language})")
        return code

    def generate_library(self, functions: List[Dict[str, str]], lang: str = "python") -> str:
        """生成可导入库文件。"""
        gen_cls = self.TARGETS.get(lang, PythonGenerator)
        if lang == "python":
            lines = ["# Auto-generated library by Matha CodeGen", ""]
            for func in functions:
                lines.append(f"def {func['name']}(")
                lines.append(f"    # {func.get('doc', '')}")
                lines.append(f"    return {func.get('expr', '0')}")
                lines.append("")
            return '\n'.join(lines)
        return ""


# ═══════════════════════════════════════════════════════════════════════════════
#  统一代码生成器
# ═══════════════════════════════════════════════════════════════════════════════

class MathaCodeGen:
    """
    统一代码生成器 — 支持多语言目标代码生成。

    用法：
        cg = MathaCodeGen()
        cg.python("x^2 + 3*x", func_name="f")
        cg.javascript("sin(x) + cos(x)")
        cg.c("sqrt(x)", return_type="double")
        cg.matha("x + y")
    """

    def __init__(self):
        self.drivers = DriverGenerator()

    def python(self, expr: str, func_name: str = "compute",
               imports: List[str] = None) -> str:
        """生成 Python 代码。"""
        gen = PythonGenerator(func_name, imports)
        gen.add_expression(expr)
        return gen.get_code()

    def javascript(self, expr: str, func_name: str = "compute",
                   as_module: bool = False) -> str:
        """生成 JavaScript 代码。"""
        gen = JavaScriptGenerator(func_name, as_module)
        gen.add_expression(expr)
        return gen.get_code()

    def c(self, expr: str, func_name: str = "compute",
          return_type: str = "double") -> str:
        """生成 C 代码。"""
        gen = CGenerator(func_name, return_type)
        gen.add_expression(expr)
        return gen.get_code()

    def matha(self, expr: str, func_name: str = "compute") -> str:
        """生成 Matha 代码。"""
        gen = MathaGenerator(func_name)
        gen.add_expression(expr)
        return gen.get_code()

    def generate_driver(self, spec: DriverSpec) -> str:
        """生成硬件驱动代码。"""
        return self.drivers.generate(spec)

    def generate_library(self, functions: List[Dict[str, str]], lang: str = "python") -> str:
        """生成可导入库。"""
        return self.drivers.generate_library(functions, lang)


