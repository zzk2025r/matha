_codegen_instance: Optional[MathaCodeGen] = None


def get_codegen() -> MathaCodeGen:
    global _codegen_instance
    if _codegen_instance is None:
        _codegen_instance = MathaCodeGen()
    return _codegen_instance


def codegen_python(expr: str, **kwargs) -> str:
    return get_codegen().python(expr, **kwargs)


def codegen_javascript(expr: str, **kwargs) -> str:
    return get_codegen().javascript(expr, **kwargs)


def codegen_c(expr: str, **kwargs) -> str:
    return get_codegen().c(expr, **kwargs)


