class MathaGenerator(CodeGenerator):
    """生成 Matha 代码。"""

    def __init__(self, func_name: str = "compute"):
        super().__init__("matha")
        self.func_name = func_name
        self._emit_header()

    def _emit_header(self):
        self.emit("# Auto-generated by Matha CodeGen")
        self.emit(f"func {self.func_name}(")
        self.block(self._emit_body)
        self.emit(")")

    def _emit_body(self):
        self.emit("    result = ...")
        self.emit("    return result")

    def add_expression(self, expr_str: str, var_name: str = "result"):
        self.emit(f"    {var_name} = {expr_str}")


