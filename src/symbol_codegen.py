class CGenerator(CodeGenerator):
    """生成 C 代码。"""

    def __init__(self, func_name: str = "compute", return_type: str = "double"):
        super().__init__("c")
        self.func_name = func_name
        self.return_type = return_type
        self._emit_header()

    def _emit_header(self):
        self.emit("/* Auto-generated by Matha CodeGen */")
        self.emit("#include <stdio.h>")
        self.emit("#include <math.h>")
        self.emit("")
        self.emit(f"{self.return_type} {self.func_name}(")
        self.emit(") {")
        self.block(self._emit_body)
        self.emit("}")

    def _emit_body(self):
        self.emit(f"{self.return_type} result = 0.0;")
        self.emit("return result;")

    def add_expression(self, expr_str: str, var_name: str = "result"):
        c_expr = self._expr_to_c(expr_str)
        self.emit(f"{var_name} = {c_expr};")

    def _expr_to_c(self, expr: str) -> str:
        return (expr
                .replace('^', "**")
                .replace('sin(', 'sin(')
                .replace('cos(', 'cos(')
                .replace('tan(', 'tan(')
                .replace('sqrt(', 'sqrt(')
                .replace('log(', 'log(')
                .replace('exp(', 'exp(')
                .replace('pi', 'M_PI')
                .replace('e', 'M_E'))


