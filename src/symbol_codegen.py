# ═══════════════════════════════════════════════════════════════════════════════
#  代码生成器基类
# ═══════════════════════════════════════════════════════════════════════════════

class CodeGenerator:
    """代码生成基类。"""

    def __init__(self, lang: str, indent: str = "  "):
        self.lang = lang
        self.indent = indent
        self._lines: List[str] = []
        self._level = 0

    def emit(self, line: str = ""):
        """输出一行代码。"""
        self._lines.append(self.indent * self._level + line)

    def block(self, body_fn):
        """代码块缩进。"""
        self._level += 1
        body_fn()
        self._level -= 1

    def get_code(self) -> str:
        """获取生成的代码。"""
        return '\n'.join(self._lines)


# ═══════════════════════════════════════════════════════════════════════════════
#  Python 代码生成
# ═══════════════════════════════════════════════════════════════════════════════

class PythonGenerator(CodeGenerator):
    """生成 Python 代码。"""

    def __init__(self, func_name: str = "compute", imports: List[str] = None):
        super().__init__("python")
        self.func_name = func_name
        self.imports = imports or []
        self._emit_header()

    def _emit_header(self):
        self.emit("# Auto-generated by Matha CodeGen")
        self.emit(f"def {self.func_name}(")
        self.emit("):")
        self.block(self._emit_body)

    def _emit_body(self):
        for imp in self.imports:
            self.emit(imp)
        self.emit("    result = ...")
        self.emit("    return result")

    def add_expression(self, expr_str: str, var_name: str = "result"):
        """添加表达式求值。"""
        py_expr = self._expr_to_python(expr_str)
        self.emit(f"    {var_name} = {py_expr}")

    def _expr_to_python(self, expr: str) -> str:
        """表达式转 Python。"""
        return (expr
                .replace('^', '**')
                .replace('sin(', 'math.sin(')
                .replace('cos(', 'math.cos(')
                .replace('tan(', 'math.tan(')
                .replace('sqrt(', 'math.sqrt(')
                .replace('log(', 'math.log(')
                .replace('exp(', 'math.exp(')
                .replace('pi', 'math.pi')
                .replace('e', 'math.e'))


