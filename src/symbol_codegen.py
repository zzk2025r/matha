class JavaScriptGenerator(CodeGenerator):
    """生成 JavaScript 代码。"""

    def __init__(self, func_name: str = "compute", as_module: bool = False):
        super().__init__("javascript")
        self.func_name = func_name
        self.as_module = as_module
        self._emit_header()

    def _emit_header(self):
        if self.as_module:
            self.emit("// Auto-generated by Matha CodeGen")
            self.emit(f"export function {self.func_name}(")
        else:
            self.emit("// Auto-generated by Matha CodeGen")
            self.emit(f"function {self.func_name}(")
        self.emit(") {")
        self.block(self._emit_body)
        self.emit("}")

    def _emit_body(self):
        self.emit("let result = 0;")
        # Math 对象映射
        self.emit("const M = Math;")

    def add_expression(self, expr_str: str, var_name: str = "result"):
        js_expr = self._expr_to_javascript(expr_str)
        self.emit(f"let {var_name} = {js_expr};")

    def _expr_to_javascript(self, expr: str) -> str:
        return (expr
                .replace('^', '**')
                .replace('sin(', 'Math.sin(')
                .replace('cos(', 'Math.cos(')
                .replace('tan(', 'Math.tan(')
                .replace('sqrt(', 'Math.sqrt(')
                .replace('log(', 'Math.log(')
                .replace('exp(', 'Math.exp(')
                .replace('pi', 'Math.PI')
                .replace('e', 'Math.E'))


