_RESOLVED: set[str] = set()
_MISSING = object()


def _resolve(name: str):
    """惰性解析一个导出名，写入本模块 __dict__ 并缓存。"""
    modname, attr, mode = _LAZY[name]
    try:
        src_mod = importlib.import_module(modname)
    except ImportError:
        if mode != "soft":
            raise
        val = None
    else:
        if attr is None:
            val = src_mod
        else:
            val = getattr(src_mod, attr, _MISSING)
            if val is _MISSING:
                if mode != "soft":
                    raise AttributeError(
                        f"module {__name__!r} has no attribute {name!r}"
                    ) from None
                val = None
    # 覆盖 importlib 自动写入的同名子模块属性，保持与 eager 绑定的可见性一致
    globals()[name] = val
    _RESOLVED.add(name)
    return val


