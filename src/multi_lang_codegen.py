#  符号简化兼容层
# ═══════════════════════════════════════════════════════════════════════════════

class SymbolCompat:
    """
    简化 >> 四重语义为单语义 + 显式转换函数。

    原始语义 → 简化后:
      >> 步进迭代   →  for x in range(a, b)
      >> 属于判断   →  x in S
      >> 路径距离   →  distance(a, b)
      >> 链式调用   →  a | b  (pipe)
    """

    MAPPING = {
        # 步进迭代: x >> S  →  for x in S
        "step_iteration": lambda x, s: f"for {x} in {s}",
        # 属于判断: x >> S  →  x in S
        "membership": lambda x, s: f"{x} in {s}",
        # 路径距离: a >> b  →  distance(a, b)
        "path_distance": lambda a, b: f"distance({a}, {b})",
        # 链式调用: a >> b  →  b(a) 或 a | b
        "pipe_call": lambda a, b: f"{b}({a})",
    }

    @staticmethod
    def simplify(expr: str) -> str:
        """将简化符号表达式转为标准表达式。"""
        # 路径距离: 单字母 a >> b → distance(a, b)
        expr = re.sub(r'\b([a-zA-Z])\s*>>\s*([a-zA-Z])\b', r'distance(\1, \2)', expr)
        # 链式调用: func >> arg → arg(func)（至少2字符）
        expr = re.sub(r'\b([a-z_][a-z_0-9]*)\s*>>\s*([a-z_][a-z_0-9]*)\b', r'\2(\1)', expr)
        return expr

    @staticmethod
    def to_pipe(expr: str) -> str:
        """转换为管道表达式 (Python 3.12+ support)。"""
        return expr.replace('>>', '|')


