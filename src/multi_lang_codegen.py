class JavaGenerator:
    """生成 Java 代码（JVM 跨平台 + 强类型）。"""

    def __init__(self, func_name: str = "compute",
                 return_type: str = "double",
                 class_name: str = "MathaCompute"):
        self.func_name = func_name
        self.return_type = return_type
        self.class_name = class_name
        self._lines: List[str] = []

    def get_code(self) -> str:
        return '\n'.join(self._lines)

    def generate_class(self, params: List[tuple], expr: str) -> str:
        """生成完整 Java 类。"""
        lines = [
            "// Auto-generated by Matha MultiLang CodeGen (Java)",
            "// JVM 跨平台 + 强类型",
            "public class " + self.class_name + " {",
        ]
        # 静态方法
        param_str = ", ".join(f"{t} {n}" for t, n in params)
        lines.append(f"    public static {self.return_type} {self.func_name}({param_str}) {{")
        java_expr = self._expr_to_java(expr)
        lines.append(f"        return {java_expr};")
        lines.append("    }")
        lines.append("")
        # main 方法
        lines.append("    public static void main(String[] args) {")
        lines.append(f'        System.out.println("{self.func_name} benchmark");')
        args_str = ", ".join(n for _, n in params)
        lines.append(f'        System.out.println("{self.func_name}({args_str}) = " + ')
        lines.append(f'            {self.func_name}({args_str}));')
        lines.append("    }")
        lines.append("}")
        return '\n'.join(lines)

    def generate_interface(self, interface_name: str, methods: List[dict]) -> str:
        """生成 Java 接口。"""
        lines = [
            "public interface " + interface_name + " {",
        ]
        for m in methods:
            param_str = ", ".join(f"{t} {n}" for t, n in m.get("params", []))
            lines.append(f"    {m['return']} {m['name']}({param_str});")
        lines.append("}")
        return '\n'.join(lines)

    def _expr_to_java(self, expr: str) -> str:
        """表达式转 Java。"""
        result = (expr
                  .replace('^', "**")  # Java 用 Math.pow
                  .replace('sin(', "Math.sin(")
                  .replace('cos(', "Math.cos(")
                  .replace('tan(', "Math.tan(")
                  .replace('sqrt(', "Math.sqrt(")
                  .replace('log(', "Math.log(")
                  .replace('exp(', "Math.exp(")
                  .replace('abs(', "Math.abs(")
                  .replace('pi', "Math.PI")
                  .replace('min(', "Math.min(")
                  .replace('max(', "Math.max("))
        return re.sub(r'\be\b', 'Math.E', result)


