class GoGenerator:
    """生成 Go 代码（原生并发 + GC + 快速编译）。"""

    def __init__(self, func_name: str = "compute",
                 return_type: str = "float64"):
        self.func_name = func_name
        self.return_type = return_type
        self._lines: List[str] = []

    def get_code(self) -> str:
        return '\n'.join(self._lines)

    def generate_function(self, params: List[tuple], expr: str) -> str:
        """生成完整函数。"""
        lines = [
            "// Auto-generated by Matha MultiLang CodeGen (Go)",
            "// 原生并发 + GC + 快速编译",
            "package main",
            "",
            "import (",
            '    "fmt"',
            '    "math"',
            ")",
            "",
        ]
        param_str = ", ".join(f"{n} {t}" for t, n in params)
        lines.append(f"func {self.func_name}({param_str}) {self.return_type} {{")
        go_expr = self._expr_to_go(expr)
        lines.append(f"    return {go_expr}")
        lines.append("}")
        lines.append("")
        # main 函数
        lines.append("func main() {")
        lines.append(f'    fmt.Println("{self.func_name} benchmark")')
        for _, name in params:
            lines.append(f'    fmt.Printf("{name} = %v\\n", {name})')
        lines.append(f'    fmt.Printf("result = %v\\n", {self.func_name}({", ".join(n for _, n in params)}))')
        lines.append("}")
        return '\n'.join(lines)

    def generate_goroutine(self, func_name: str, args: List[tuple]) -> str:
        """生成 goroutine 并发示例。"""
        param_str = ", ".join(f"{n} {t}" for t, n in args)
        return f"""func run_{func_name}() {{
    ch := make(chan {self.return_type})
    go func() {{
        ch <- {func_name}({", ".join(n for _, n in args)})
    }}()
    result := <-ch
    fmt.Printf("{func_name} result = %v\\n", result)
}}"""

    def _expr_to_go(self, expr: str) -> str:
        """表达式转 Go。"""
        result = (expr
                  .replace('^', "**")  # Go 用 math.Pow
                  .replace('sin(', "math.Sin(")
                  .replace('cos(', "math.Cos(")
                  .replace('tan(', "math.Tan(")
                  .replace('sqrt(', "math.Sqrt(")
                  .replace('log(', "math.Log(")
                  .replace('exp(', "math.Exp(")
                  .replace('abs(', "math.Abs(")
                  .replace('pi', "math.Pi")
                  .replace('min(', "math.Min(")
                  .replace('max(', "math.Max("))
        return re.sub(r'\be\b', 'math.E', result)


