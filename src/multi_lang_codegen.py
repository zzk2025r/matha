@dataclass
class CodeGenResult:
    """代码生成结果。"""
    language: str
    code: str
    executable: bool = False  # 是否可直接执行
    benchmark: str = ""       # 性能基准数据


class MultiLangCodeGen:
    """多语言代码生成统一入口。"""

    # 语言注册表
    _generators = {
        "python": "symbol_codegen:PythonGenerator",
        "javascript": "symbol_codegen:JavaScriptGenerator",
        "c": "symbol_codegen:CGenerator",
        "cpp": "__main__:CppGenerator",
        "rust": "__main__:RustGenerator",
        "go": "__main__:GoGenerator",
        "java": "__main__:JavaGenerator",
        "matha": "symbol_codegen:MathaGenerator",
    }

    def __init__(self):
        self._results: Dict[str, CodeGenResult] = {}

    def generate(self, language: str, func_name: str,
                 params: List[tuple], expr: str,
                 return_type: str = "double") -> CodeGenResult:
        """生成指定语言的代码。"""
        lang = language.lower()
        if lang == "cpp":
            gen = CppGenerator(func_name, return_type)
            code = gen.generate_function(params, expr)
        elif lang == "rust":
            gen = RustGenerator(func_name, return_type)
            code = gen.generate_function(params, expr)
        elif lang == "go":
            gen = GoGenerator(func_name, return_type)
            code = gen.generate_function(params, expr)
        elif lang == "java":
            gen = JavaGenerator(func_name, return_type)
            code = gen.generate_class(params, expr)
        else:
            # 委托给原有生成器
            from src.symbol_codegen import (
                PythonGenerator, JavaScriptGenerator, CGenerator, MathaGenerator
            )
            generators = {
                "python": PythonGenerator(func_name),
                "javascript": JavaScriptGenerator(func_name),
                "c": CGenerator(func_name, return_type),
                "matha": MathaGenerator(func_name),
            }
            gen = generators.get(lang)
            if gen is None:
                return CodeGenResult(language, f"# Unsupported language: {lang}", False)
            gen.add_expression(expr)
            code = gen.get_code()

        result = CodeGenResult(
            language=lang,
            code=code,
            executable=lang in ("c", "cpp", "rust", "go", "java"),
        )
        self._results[lang] = result
        return result

    def generate_all(self, func_name: str, params: List[tuple],
                     expr: str, return_type: str = "double") -> Dict[str, CodeGenResult]:
        """生成所有支持语言的代码。"""
        languages = ["python", "javascript", "c", "cpp", "rust", "go", "java", "matha"]
        for lang in languages:
            self.generate(lang, func_name, params, expr, return_type)
        return self._results

    def get_result(self, language: str) -> Optional[CodeGenResult]:
        return self._results.get(language)

    def summary(self) -> str:
        """生成生成摘要。"""
        lines = ["=== Matha 多语言代码生成摘要 ==="]
        for lang, result in self._results.items():
            lines.append(f"  [{lang.upper()}] {len(result.code)} bytes, "
                        f"executable={'Yes' if result.executable else 'No'}")
        return '\n'.join(lines)


