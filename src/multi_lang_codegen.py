class RustGenerator:
    """生成 Rust 代码（内存安全 + 零成本抽象）。"""

    def __init__(self, func_name: str = "compute",
                 return_type: str = "f64",
                 generic: bool = False):
        self.func_name = func_name
        self.return_type = return_type
        self.generic = generic
        self._lines: List[str] = []

    def get_code(self) -> str:
        return '\n'.join(self._lines)

    def generate_function(self, params: List[tuple], expr: str) -> str:
        """生成完整函数。"""
        param_str = ", ".join(f"{n}: {t}" for t, n in params)
        lines = [
            "// Auto-generated by Matha MultiLang CodeGen (Rust)",
            "// 内存安全 + 零成本抽象",
            "#[inline]",
            f"pub fn {self.func_name}({param_str}) -> {self.return_type} {{",
        ]
        rust_expr = self._expr_to_rust(expr)
        lines.append(f"    {rust_expr}")
        lines.append("}")
        lines.append("")
        lines.append(f"// 测试")
        lines.append(f"fn test_{self.func_name}() {{")
        lines.append(f"    let result = {self.func_name}({', '.join(n for _, n in params)});")
        lines.append(f"    assert!((result - {self._get_expected(params)}).abs() < 1e-9);")
        lines.append(f"}}")
        lines.append(f"")
        lines.append(f"fn main() {{")
        lines.append(f"    println!(\"Matha Rust Benchmark\");")
        lines.append(f"    test_{self.func_name}();")
        lines.append(f"    println!(\"All tests passed!\");")
        lines.append(f"}}")
        return '\n'.join(lines)

    def generate_trait(self, trait_name: str, methods: List[dict]) -> str:
        """生成 Rust Trait。"""
        lines = [
            "// Auto-generated by Matha MultiLang CodeGen (Rust)",
            f"pub trait {trait_name} {{",
        ]
        for m in methods:
            param_str = ", ".join(f"{n}: {t}" for t, n in m.get("params", []))
            lines.append(f"    fn {m['name']}({param_str}) -> {m['return']};")
        lines.append("}")
        lines.append("}")
        return '\n'.join(lines)

    def generate_main(self) -> str:
        """生成 main 测试入口。"""
        return """fn main() {
    println!("Matha Rust Benchmark");
    test_compute();
    println!("All tests passed!");
}"""

    def _expr_to_rust(self, expr: str) -> str:
        """表达式转 Rust。"""
        result = (expr
                  .replace('^', "**")
                  .replace('sin(', "f64::sin(")
                  .replace('cos(', "f64::cos(")
                  .replace('tan(', "f64::tan(")
                  .replace('sqrt(', "f64::sqrt(")
                  .replace('log(', "f64::ln(")
                  .replace('exp(', "f64::exp(")
                  .replace('abs(', "f64::abs(")
                  .replace('pi', "std::f64::consts::PI")
                  .replace('min(', "f64::min(")
                  .replace('max(', "f64::max("))
        return re.sub(r'\be\b', 'std::f64::consts::E', result)

    def _get_expected(self, params: List[tuple]) -> str:
        """生成预期值占位符。"""
        return "0.0"


