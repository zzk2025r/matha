class CppGenerator:
    """生成 C++ 代码（支持面向对象 + 模板 + STL）。"""

    def __init__(self, func_name: str = "compute",
                 return_type: str = "double",
                 use_templates: bool = False):
        self.func_name = func_name
        self.return_type = return_type
        self.use_templates = use_templates
        self._lines: List[str] = []
        self._level = 0

    def emit(self, line: str = ""):
        self._lines.append("    " * self._level + line)

    def block(self, fn):
        self._level += 1
        fn()
        self._level -= 1

    def get_code(self) -> str:
        return '\n'.join(self._lines)

    def generate_function(self, params: List[tuple], expr: str) -> str:
        """生成完整函数。"""
        lines = [
            "// Auto-generated by Matha MultiLang CodeGen (C++)",
            "#include <iostream>",
            "#include <cmath>",
            "#include <algorithm>",
            "#include <vector>",
            "#include <numeric>",
            "",
        ]
        # 函数签名
        param_str = ", ".join(f"{t} {n}" for t, n in params)
        lines.append(f"{self.return_type} {self.func_name}({param_str}) {{")
        self._lines = lines
        self._level = 1
        # 局部变量声明
        self.emit(f"{self.return_type} result = 0.0;")
        # 表达式
        cpp_expr = self._expr_to_cpp(expr)
        self.emit(f"result = {cpp_expr};")
        self.emit("return result;")
        self.emit("}")
        return self.get_code()

    def generate_class(self, class_name: str, methods: List[dict]) -> str:
        """生成 C++ 类。"""
        lines = [
            "// Auto-generated by Matha MultiLang CodeGen (C++)",
            f"class {class_name} {{",
            "public:",
        ]
        for m in methods:
            param_str = ", ".join(f"{t} {n}" for t, n in m.get("params", []))
            lines.append(f"    {m['return']} {m['name']}({param_str}) {{")
            lines.append(f"        return {self._expr_to_cpp(m.get('expr', '0'))};")
            lines.append("    }")
        lines.append("};")
        return '\n'.join(lines)

    def generate_main(self, func_name: str, test_cases: List[tuple]) -> str:
        """生成 main 测试函数。"""
        lines = [
            "int main() {",
            f"    std::cout << \"{func_name} benchmark\" << std::endl;",
        ]
        for args, expected in test_cases:
            args_str = ", ".join(str(a) for a in args)
            lines.append(f'    std::cout << "{func_name}({args_str}) = " '
                        f'<< {func_name}({args_str}) << std::endl;')
        lines.append("    return 0;")
        lines.append("}")
        return '\n'.join(lines)

    def _expr_to_cpp(self, expr: str) -> str:
        """表达式转 C++。"""
        result = (expr
                  .replace('^', "**")  # C++20 支持幂运算符
                  .replace('sin(', "std::sin(")
                  .replace('cos(', "std::cos(")
                  .replace('tan(', "std::tan(")
                  .replace('sqrt(', "std::sqrt(")
                  .replace('log(', "std::log(")
                  .replace('exp(', "std::exp(")
                  .replace('abs(', "std::abs(")
                  .replace('pi', "M_PI")
                  .replace('min(', "std::min(")
                  .replace('max(', "std::max("))
        return re.sub(r'\be\b', 'M_E', result)


