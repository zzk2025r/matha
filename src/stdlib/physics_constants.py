# -*- coding: utf-8 -*-
"""统一物理常量库

所有 domain 模块和 formula_system 应从此处导入物理常量，
避免重复定义和数值不一致。
"""
from __future__ import annotations


class PhysicalConstants:
    """统一物理常量表。所有物理公式使用此处的常量，确保一致性。"""

    # ── 基本常量 ──────────────────────────────────────────
    c = 299792458.0            # 光速 m/s
    G = 6.67430e-11            # 万有引力常数 N·m²/kg²
    g = 9.80665                # 标准重力加速度 m/s²
    h_planck = 6.62607015e-34  # 普朗克常数 J·s
    hbar = 1.054571817e-34     # 约化普朗克常数 J·s
    e_charge = 1.602176634e-19 # 元电荷 C
    k_B = 1.380649e-23         # 玻尔兹曼常数 J/K
    N_A = 6.02214076e23        # 阿伏伽德罗常数 mol⁻¹
    R_gas = 8.314462618        # 理想气体常数 J/(mol·K)
    sigma_sb = 5.670374419e-8  # 斯特藩-玻尔兹曼常数 W/(m²·K⁴)
    eps0 = 8.8541878128e-12    # 真空介电常数 F/m
    mu0 = 1.25663706212e-6     # 真空磁导率 H/m
    k_coulomb = 8.9875517923e9 # 库仑常数 N·m²/C²

    # ── 粒子质量 ──────────────────────────────────────────
    m_e = 9.1093837015e-31     # 电子质量 kg
    m_p = 1.67262192369e-27    # 质子质量 kg
    m_n = 1.67492749804e-27    # 中子质量 kg

    # ── 天文常数 ──────────────────────────────────────────
    M_earth = 5.972e24         # 地球质量 kg
    M_sun = 1.989e30           # 太阳质量 kg
    R_earth = 6.371e6          # 地球半径 m
    AU = 1.495978707e11        # 天文单位 m
    LY = 9.4607304725808e15    # 光年 m
    PC = 3.0856775814913673e16 # 秒差距 m

    # ── 原子物理 ──────────────────────────────────────────
    a0 = 5.29177210903e-11     # 玻尔半径 m
    Ry = 2.1798723611035e-18   # 里德伯能量 J
    alpha = 7.2973525693e-3    # 精细结构常数


# 单例实例
C = PhysicalConstants()

# 兼容旧域名（domain 模块可继续引用）
G_GRAV = C.G
C_LIGHT = C.c
H_PLANCK = C.h_planck
E_CHARGE = C.e_charge
N_A = C.N_A
R_GAS = C.R_gas
SIGMA_SB = C.sigma_sb
